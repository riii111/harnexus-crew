const LAST_CODE_POINT = 0x10ffff;

const rangesOf = (matches: RegExp) => {
  const ranges: number[] = [];
  let start = -1;
  for (let code = 0; code <= LAST_CODE_POINT + 1; code += 1) {
    const hit =
      code <= LAST_CODE_POINT && matches.test(String.fromCodePoint(code));
    if (hit && start === -1) start = code;
    if (!hit && start !== -1) {
      ranges.push(start, code - 1);
      start = -1;
    }
  }

  return ranges;
};

export const letterRanges = () => rangesOf(/^\p{L}$/u);

export const numberRanges = () => rangesOf(/^\p{N}$/u);

const hex = (code: number) => `0x${code.toString(16).toUpperCase()}`;

const listing = (ranges: readonly number[]) => {
  const lines: string[] = [];
  for (let at = 0; at < ranges.length; at += 8)
    lines.push(
      `  ${ranges
        .slice(at, at + 8)
        .map(hex)
        .join(", ")},`,
    );
  return lines.join("\n");
};

export const unicodeTablesSource = () =>
  `// Generated by test/native/unicode-tables.ts from the \\p{L} and \\p{N} classes of the pinned Bun, so the native build classifies code points as the TypeScript build does.
// Change the generator, not this file; \`bun test/native/unicode-tables.ts > native/text/unicode_tables.mbt\` rewrites it.

///|
let letter_ranges : FixedArray[Int] = [
${listing(letterRanges())}
]

///|
let number_ranges : FixedArray[Int] = [
${listing(numberRanges())}
]
`;

if (import.meta.main) process.stdout.write(unicodeTablesSource());
